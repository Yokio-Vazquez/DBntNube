ALTER TABLE game_metrics
    ADD COLUMN IF NOT EXISTS deleted_at TIMESTAMPTZ;

CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id VARCHAR(120),
    action VARCHAR(80) NOT NULL,
    resource_type VARCHAR(80) NOT NULL,
    resource_id VARCHAR(120),
    outcome VARCHAR(20) NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT audit_logs_outcome_valid CHECK (outcome IN ('success', 'failure')),
    CONSTRAINT audit_logs_action_not_blank CHECK (length(trim(action)) > 0),
    CONSTRAINT audit_logs_resource_type_not_blank CHECK (length(trim(resource_type)) > 0)
);

CREATE OR REPLACE FUNCTION reject_audit_log_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'audit log entries are append-only';
END;
$$;

DROP TRIGGER IF EXISTS audit_logs_append_only ON audit_logs;
CREATE TRIGGER audit_logs_append_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION reject_audit_log_mutation();

CREATE OR REPLACE FUNCTION soft_delete_metric(target_id BIGINT)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
    UPDATE public.game_metrics
    SET deleted_at = CURRENT_TIMESTAMP
    WHERE id = target_id AND deleted_at IS NULL;
    RETURN FOUND;
END;
$$;

REVOKE ALL ON FUNCTION soft_delete_metric(BIGINT) FROM PUBLIC;