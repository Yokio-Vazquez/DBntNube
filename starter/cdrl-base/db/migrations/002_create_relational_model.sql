CREATE TABLE IF NOT EXISTS metric_definitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    metric_name VARCHAR(30) NOT NULL,
    unit VARCHAR(20) NOT NULL,
    description VARCHAR(200) NOT NULL,

    CONSTRAINT metric_definitions_name_unique UNIQUE (metric_name),
    CONSTRAINT metric_definitions_name_unit_unique UNIQUE (metric_name, unit),
    CONSTRAINT metric_definitions_name_not_blank CHECK (length(trim(metric_name)) > 0),
    CONSTRAINT metric_definitions_unit_not_blank CHECK (length(trim(unit)) > 0),
    CONSTRAINT metric_definitions_description_not_blank CHECK (length(trim(description)) > 0)
);

-- Upgrade databases created by the first M02 draft, which used code/min_value/max_value.
ALTER TABLE metric_definitions
    ADD COLUMN IF NOT EXISTS metric_name VARCHAR(30),
    ADD COLUMN IF NOT EXISTS description VARCHAR(200);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'metric_definitions'
          AND column_name = 'code'
    ) THEN
        UPDATE metric_definitions
        SET metric_name = COALESCE(metric_name, code)
        WHERE metric_name IS NULL;
    END IF;

    UPDATE metric_definitions
    SET description = COALESCE(description, 'Definicion de metrica CDRL')
    WHERE description IS NULL;
END
$$;

ALTER TABLE metric_definitions
