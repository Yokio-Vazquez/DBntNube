CREATE TABLE IF NOT EXISTS platforms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(80) NOT NULL,
    manufacturer VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT platforms_code_unique UNIQUE (code),
    CONSTRAINT platforms_code_not_blank CHECK (length(trim(code)) > 0),
    CONSTRAINT platforms_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT platforms_manufacturer_not_blank CHECK (length(trim(manufacturer)) > 0)
);

CREATE TABLE IF NOT EXISTS game_platforms (
    game_id BIGINT NOT NULL,
    platform_id BIGINT NOT NULL,
    release_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'available',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT game_platforms_pk PRIMARY KEY (game_id, platform_id),
    CONSTRAINT game_platforms_game_fk
        FOREIGN KEY (game_id) REFERENCES games (id) ON DELETE CASCADE,
    CONSTRAINT game_platforms_platform_fk
        FOREIGN KEY (platform_id) REFERENCES platforms (id) ON DELETE RESTRICT,
    CONSTRAINT game_platforms_status_valid
        CHECK (status IN ('planned', 'available', 'retired')),
    CONSTRAINT game_platforms_release_date_valid
        CHECK (release_date >= DATE '1970-01-01')
);

